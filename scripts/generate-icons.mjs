#!/usr/bin/env node
/**
 * Generate a Lucide subset containing only the icons referenced in `src/`.
 *
 * The full `@iconify-json/lucide/icons.json` is ~550 KB and lands in the main
 * client bundle. The app references ~300 glyphs, so registering a generated
 * subset cuts the bundle substantially while keeping icons offline + SSR-safe.
 *
 * Run `pnpm icons` after adding or removing icon names.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE_DIR = new URL('../src', import.meta.url).pathname;
const OUTPUT = new URL('../src/lib/icons-subset.generated.ts', import.meta.url).pathname;
const FULL_ICONS = new URL('../node_modules/@iconify-json/lucide/icons.json', import.meta.url)
	.pathname;

/** Names that appear in prose/comments rather than in rendered markup. */
const IGNORE = new Set(['foo']);

const ICON_RE = /(?:i-lucide-([a-z0-9-]+)|lucide:([a-z0-9-]+))/g;

function walk(dir, out = []) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) {
			if (!['node_modules', '.svelte-kit', 'vendor'].includes(entry.name)) walk(path, out);
		} else if (/\.(svelte|ts)$/.test(entry.name) && !entry.name.endsWith('.generated.ts')) {
			out.push(path);
		}
	}
	return out;
}

const used = new Set();
for (const file of walk(SOURCE_DIR)) {
	const source = readFileSync(file, 'utf8');
	for (const match of source.matchAll(ICON_RE)) {
		const name = match[1] ?? match[2];
		if (name && !IGNORE.has(name)) used.add(name);
	}
}

const full = JSON.parse(readFileSync(FULL_ICONS, 'utf8'));
const icons = {};
const aliases = {};
const missing = [];

function add(name) {
	if (icons[name] || aliases[name]) return;
	if (full.icons?.[name]) {
		icons[name] = full.icons[name];
		return;
	}
	const alias = full.aliases?.[name];
	if (alias) {
		aliases[name] = alias;
		// An alias must resolve to an icon that ships in the subset.
		if (alias.parent) add(alias.parent);
		return;
	}
	missing.push(name);
}

for (const name of [...used].sort()) add(name);

const data = {
	prefix: full.prefix,
	icons,
	...(Object.keys(aliases).length ? { aliases } : {}),
	width: full.width,
	height: full.height
};

const banner = `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.\n// Run \`pnpm icons\` after adding/removing icon names.\n`;
writeFileSync(OUTPUT, `${banner}export const LUCIDE_SUBSET = ${JSON.stringify(data)};\n`);

console.log(
	`[icons] ${Object.keys(icons).length} icons (${Object.keys(aliases).length} aliases) -> ${OUTPUT.replace(process.cwd(), '.')}`
);
if (missing.length) console.warn(`[icons] not in Lucide ${full.prefix}: ${missing.join(', ')}`);
